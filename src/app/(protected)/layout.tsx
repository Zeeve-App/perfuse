import type { Metadata } from "next";
import "../globals.css";
import { headers } from "next/headers";
import { redirect } from "next/navigation";
import { dmSans, poppins } from "@/utils/fonts";
import LayoutProvider from "@/providers/layout-provider";
import ToastProvider from "@/providers/toast-provider";
import ModalProvider from "@/providers/modal-provider";
import { authFromHeader, themeFromHeader } from "@/middleware";

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const header = headers();
  const data = await authFromHeader(header);
  const theme = themeFromHeader(header);
  if (!data?.email) {
    return redirect("/login");
  }

  return (
    <html lang="en">
      <head>
        <link rel="icon" href="/logo.png" />
      </head>
      <body className={`${dmSans.variable} ${poppins.variable} ${theme === "dark" ? "dark" : ""} font-poppins`}>
        <ToastProvider>
          <ModalProvider />
          <LayoutProvider>{children}</LayoutProvider>
        </ToastProvider>
      </body>
    </html>
  );
}
